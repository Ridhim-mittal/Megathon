const fill = (text, vars) =>
  vars ? text.replace(/\{(\w+)\}/g, (all, k) => (vars[k] == null ? all : String(vars[k]))) : text;

export function gyaanText(lang, key, vars) {
  const value = GYAAN_STRINGS[lang]?.[key] ?? GYAAN_STRINGS.en[key] ?? key;
  return typeof value === "string" ? fill(value, vars) : value;
}

// Widgets receive only { lang }, so they use this helper directly.
export const textFor = (lang) => (key, vars) => gyaanText(lang, key, vars);

export function useGyaanText() {
  const T = useT();
  return { ...T, g: textFor(T.lang) };
}
