const fill = (text, vars) =>
  vars ? text.replace(/\{(\w+)\}/g, (all, k) => (vars[k] == null ? all : String(vars[k]))) : text;

export function phoneText(lang, key, vars) {
  const value = PHONE_STRINGS[lang]?.[key] ?? PHONE_STRINGS.en[key] ?? key;
  return fill(value, vars);
}

// const { s, lang, name } = usePhoneText(); s("age", { age: 19 })
export function usePhoneText() {
  const T = useT();
  const lang = T.lang;
  return {
    ...T,
    s: (key, vars) => phoneText(lang, key, vars),
    name: (id) => INSTRUMENT_NAMES[id]?.[lang] ?? INSTRUMENT_NAMES[id]?.en ?? id,
  };
}
